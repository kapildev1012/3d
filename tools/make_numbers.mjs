#!/usr/bin/env node
/**
 * Write results/paper/numbers.tex: one \newcommand per number quoted in the
 * paper text, generated from results/paper/summary.json so that prose and
 * tables can never disagree with the measured data.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const summary = JSON.parse(readFileSync(path.join(root, 'results', 'paper', 'summary.json'), 'utf8'));
const lines = ['% Auto-generated by tools/make_numbers.mjs -- do not edit by hand.'];
const fixed = (v, d) => (Number.isFinite(v) ? v.toFixed(d) : '--');
const sci = v => {
  if (!Number.isFinite(v)) return '--';
  const [m, e] = v.toExponential(1).split('e');
  return `${m}\\times 10^{${Number(e)}}`;
};
const def = (name, value) => lines.push(`\\newcommand{\\${name}}{${value}}`);
const cell = (rows, label, key) => rows.find(r => r.label.startsWith(label))?.cells?.[key];

const nominal = summary.nominal || [];
const byKey = key => nominal.find(r => r.key === key);
for (const [key, tag] of [['sgt', 'Sgt'], ['heuristic', 'Heu'], ['lqr', 'Lqr'], ['ilqr', 'Ilqr'], ['mpc', 'Mpc'], ['legacyAssisted', 'Leg']]) {
  const row = byKey(key);
  if (!row) continue;
  def(`n${tag}Speed`, fixed(row.cells.speed.mean, 3));
  def(`n${tag}SpeedStd`, fixed(row.cells.speed.std, 3));
  def(`n${tag}Progress`, fixed(row.cells.progress.mean, 2));
  def(`n${tag}Rmse`, fixed(row.cells.rmse.mean, 3));
  def(`n${tag}Success`, fixed(100*row.cells.success.mean, 0));
  def(`n${tag}Aid`, fixed(100*row.cells.assistShare.mean, 0));
  def(`n${tag}Cot`, fixed(row.cells.cot.mean, 1));
  def(`n${tag}SolveMs`, fixed(row.cells.solveMsMean.mean, 2));
  def(`n${tag}SolveMax`, fixed(row.cells.solveMsMax.mean, 1));
  def(`n${tag}Residual`, sci(row.cells.maxResidual.mean));
  def(`n${tag}Bar`, sci(row.cells.maxBarError.mean));
}
const physics = summary.physics || [];
const phys = (label, key) => cell(physics, label, key);
def('pDaeResidual', sci(phys('DAE + Alg.~1, energy row', 'maxResidual')?.mean));
def('pDaeBar', sci(phys('DAE + Alg.~1, energy row', 'maxBarError')?.mean));
def('pNoERowResidual', sci(phys('DAE + Alg.~1, constr.', 'maxResidual')?.mean));
def('pLegacyResidual', sci(phys('Penalty + SHAKE', 'maxResidual')?.mean));
def('pDaeNum', sci(phys('DAE + Alg.~1, energy row', 'numericalWork')?.mean));
def('pNoERowNum', sci(phys('DAE + Alg.~1, constr.', 'numericalWork')?.mean));
def('pLegacyNum', sci(phys('Penalty + SHAKE', 'numericalWork')?.mean));
def('pLegacyBar', sci(phys('Penalty + SHAKE', 'maxBarError')?.mean));
def('pDaeStepDrift', sci(phys('DAE + Alg.~1, energy row', 'maxStepDrift')?.mean));
def('pDaeDriftAbs', fixed(phys('DAE + Alg.~1, energy row', 'driftAbs')?.mean, 1));
def('pNoERowDriftAbs', fixed(phys('DAE + Alg.~1, constr.', 'driftAbs')?.mean, 1));
def('pLegacyDriftAbs', fixed(phys('Penalty + SHAKE', 'driftAbs')?.mean, 1));
def('pLegacyStepDrift', sci(phys('Penalty + SHAKE', 'maxStepDrift')?.mean));
def('pLegacyAidShare', fixed(100*(phys('Legacy + assists', 'assistShare')?.mean), 0));
// Time-step convergence check (tools/drift_check.mjs), merged from partial files
{
  const dir = path.join(root, 'results', 'paper');
  const merged = {};
  for (const f of readdirSync(dir).filter(f => /^drift_check.*\.json$/.test(f))) Object.assign(merged, JSON.parse(readFileSync(path.join(dir, f), 'utf8')));
  const tag = { dae2: 'DaeTwo', dae1: 'DaeOne', legacy2: 'LegTwo', legacy1: 'LegOne' };
  for (const [key, name] of Object.entries(tag)) {
    const d = merged[key];
    if (!d) continue;
    def(`dc${name}Abs`, fixed(d.driftAbs, 1));
    def(`dc${name}Signed`, fixed(d.driftSigned, 1));
    def(`dc${name}Rate`, fixed(d.driftRateW, 2));
    def(`dc${name}Step`, sci(d.maxStepDrift));
    def(`dc${name}Cable`, fixed(d.cableWork, 1));
  }
}
// Ablation and stress rows (matched by label prefix)
const abl = summary.ablation || [];
for (const [prefix, tag] of [['SGT (full)', 'Full'], ['w/o payload', 'NoPayload'], ['w/o feasibility', 'NoFeas'], ['w/o bar geometric', 'NoGeo'],
  ['sparse', 'Sparse'], ['DAE w/o energy', 'NoERow'], ['legacy SHAKE', 'Legacy']]) {
  const row = abl.find(r => r.label.startsWith(prefix));
  if (!row) continue;
  def(`a${tag}Speed`, fixed(row.cells.speed.mean, 3));
  def(`a${tag}SpeedStd`, fixed(row.cells.speed.std, 3));
  def(`a${tag}Cot`, fixed(row.cells.cot.mean, 1));
  def(`a${tag}Success`, fixed(100*row.cells.success.mean, 0));
  def(`a${tag}Tips`, fixed(row.cells.tips.mean, 1));
}
const stress = summary.stress || [];
for (const [prefix, tag] of [['Nominal', 'Nom'], ['Lateral impulse', 'Imp'], ['Step push', 'Push'], ['Gaussian', 'Gauss'], ['Laplace', 'Lap'],
  ['Sensor outliers', 'Out'], ['Cable stiffness', 'Stiff'], ['Friction', 'Fric'], ['Payload mass', 'Mass'], ['Actuator delay', 'Delay']]) {
  const row = stress.find(r => r.label.startsWith(prefix));
  if (!row) continue;
  def(`s${tag}Speed`, fixed(row.cells.sgtSpeed.mean, 3));
  def(`s${tag}SpeedStd`, fixed(row.cells.sgtSpeed.std, 3));
  def(`s${tag}Success`, fixed(100*row.cells.sgtSuccess.mean, 0));
  def(`s${tag}Rec`, fixed(row.cells.sgtRecovery.mean, 2));
}
const gen = summary.generalization || [];
for (const [prefix, tag] of [['Level 4: SGT', 'Four'], ['Level 7: SGT', 'Seven']]) {
  const row = gen.find(r => r.label.startsWith(prefix));
  if (!row) continue;
  def(`g${tag}Speed`, fixed(row.cells.speed.mean, 3));
  def(`g${tag}SpeedStd`, fixed(row.cells.speed.std, 3));
  def(`g${tag}Residual`, sci(row.cells.maxResidual.mean));
}
const best = key => Math.max(...nominal.filter(r => !r.reference && r.key !== 'sgt').map(r => r.cells[key].mean));
def('baseBestProgress', fixed(best('progress'), 2));
def('baseBestSpeed', fixed(best('speed'), 4));
const sgt = byKey('sgt'), heu = byKey('heuristic');
if (sgt && heu && heu.cells.speed.mean > 0) def('speedRatio', fixed(sgt.cells.speed.mean/heu.cells.speed.mean, 0));
writeFileSync(path.join(root, 'results', 'paper', 'numbers.tex'), lines.join('\n')+'\n');
console.log(`[numbers] ${lines.length-1} macros`);
