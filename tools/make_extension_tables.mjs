#!/usr/bin/env node
/**
 * Numbers and tables for the MPC + GPS (guided policy search) and
 * suspension-integrity sections of the paper, generated from
 *   results/guided_policy/evaluation.json   (tools/train_guided_policy.mjs)
 *   results/shield_study/runs.json          (tools/run_shield_study.mjs)
 * Writes results/paper/numbers_ext.tex and results/paper/tables_ext.tex.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => JSON.parse(readFileSync(path.join(root, p), 'utf8'));
const policyEval = read('results/guided_policy/evaluation.json');
const training = read('results/guided_policy/training.json');
const runs = read('results/shield_study/runs.json');

const stats = values => {
  const mean = values.reduce((s, v) => s+v, 0)/values.length;
  const std = Math.sqrt(values.reduce((s, v) => s+(v-mean)**2, 0)/Math.max(1, values.length-1));
  return { mean, std };
};
const f = (v, d) => Number(v).toFixed(d);
const pm = (s, d) => `${f(s.mean, d)}\\,$\\pm$\\,${f(s.std, d)}`;
const macros = [];
const def = (name, value) => macros.push(`\\newcommand{\\${name}}{${value}}`);

// ---------------------------------------------------------------- guided policy search
const ev = policyEval.evaluation;
const by = mode => ev.filter(r => r.mode === mode);
const pol = { sgt: by('sgt'), teacher: by('teacher'), policy: by('policy') };
const pS = key => Object.fromEntries(Object.entries(pol).map(([k, rows]) => [k, stats(rows.map(r => r[key]))]));
const prog = pS('progress'), tips = pS('tips'), aborts = pS('aborts'), ms = pS('controllerMs'), xt = pS('crossTrack');
const last = training[training.length-1];
def('gpsIterations', training.length);
def('gpsSamples', `${Math.round(last.samples/1000)}k`);
def('gpsEvalConditions', pol.policy.length);
def('gpsPolicyProgress', f(prog.policy.mean, 2));
def('gpsSgtProgress', f(prog.sgt.mean, 2));
def('gpsTeacherProgress', f(prog.teacher.mean, 2));
def('gpsRatio', f(100*prog.policy.mean/prog.sgt.mean, 0));
def('gpsTeacherRatio', f(100*prog.policy.mean/prog.teacher.mean, 0));
def('gpsPolicyMs', f(ms.policy.mean, 2));
def('gpsSgtMs', f(ms.sgt.mean, 2));
def('gpsPolicyAborts', f(aborts.policy.mean, 2));
const bestPolicyRow = pol.policy.reduce((a, b) => (b.progress-pol.sgt.find(s => s.seed === b.seed).progress > a.progress-pol.sgt.find(s => s.seed === a.seed).progress ? b : a));
def('gpsBestPolicy', f(bestPolicyRow.progress, 2));
def('gpsBestSgt', f(pol.sgt.find(s => s.seed === bestPolicyRow.seed).progress, 2));

const gpsTable = `% Auto-generated by tools/make_extension_tables.mjs -- do not edit by hand.
\\begin{table}[t]
\\centering
\\caption{MPC + GPS (MPC-guided policy search): held-out evaluation, ${pol.policy.length} conditions (Levels 1 and 3, straight and $\\pm6$\\,m offset goals, unseen seeds), 20\\,s cable-only runs, mean\\,$\\pm$\\,std.}
\\label{tab:gps}
\\setlength{\\tabcolsep}{3pt}
\\footnotesize
\\begin{tabular}{lcccc}
\\toprule
Method & $\\Delta y$ (m) & Tips & Aborts & $t_{\\mathrm{ctrl}}$ (ms) \\\\
\\midrule
SGT & ${pm(prog.sgt, 2)} & ${pm(tips.sgt, 1)} & ${pm(aborts.sgt, 2)} & ${pm(ms.sgt, 2)} \\\\
MPC teacher ($\\lambda=0$) & ${pm(prog.teacher, 2)} & ${pm(tips.teacher, 1)} & ${pm(aborts.teacher, 2)} & ${pm(ms.teacher, 2)} \\\\
MPC + GPS policy & ${pm(prog.policy, 2)} & ${pm(tips.policy, 1)} & ${pm(aborts.policy, 2)} & ${pm(ms.policy, 2)} \\\\
\\bottomrule
\\end{tabular}
\\end{table}
`;

// ---------------------------------------------------------------- suspension-integrity filter
const conditions = [...new Set(runs.map(r => r.condition))];
const pick = (mode, shield, key) => conditions.map(c => runs.find(r => r.condition === c && r.mode === mode && r.shield === shield)[key]);
const rowsSpec = [
  ['progress', '$\\Delta y$ (m)', 'max', 2],
  ['slackPct', 'Payload-cable slack time (\\%)', 'min', 1],
  ['meanCoreTension', 'Mean payload-cable tension (N)', 'max', 1],
  ['aborts', 'Aborted tip cycles', 'min', 1],
  ['rattleMm', 'Payload rattle RMS (mm)', 'min', 1],
  ['payloadAccelP99g', 'Payload accel.\\ 99th pct (g)', 'min', 2],
  ['minClearance', 'Min payload--rod clearance (m)', 'max', 3],
  ['maxOuterTension', 'Max outer-cable tension (N)', 'min', 0],
  ['controllerMs', '$t_{\\mathrm{ctrl}}$ (ms)', 'min', 2]
];
const better = (on, off, dir) => on.filter((v, i) => (dir === 'max' ? v > off[i] : v < off[i])).length;
let shieldRows = '';
for (const [key, label, dir, d] of rowsSpec) {
  const cells = [];
  for (const mode of ['sgt_tipping', 'guided_policy']) {
    const off = pick(mode, 'off', key), on = pick(mode, 'on', key);
    cells.push(`${pm(stats(off), d)} & ${pm(stats(on), d)} & ${key === 'controllerMs' ? '--' : `${better(on, off, dir)}/${conditions.length}`}`);
  }
  shieldRows += `${label} & ${cells.join(' & ')} \\\\\n`;
}
const shieldTable = `\\begin{table*}[t]
\\centering
\\caption{Suspension-integrity filter, ${conditions.length} paired conditions (3 seeds on Level 1, 2 on Level 3, push, impulse, payload $+30\\,\\%$, 100\\,ms delay, cable stiffness $-20\\,\\%$), 20\\,s cable-only runs, mean\\,$\\pm$\\,std over conditions. \`\`Better'' counts paired conditions in which the filter improved the metric. Metrics exclude the first second (initial settling).}
\\label{tab:shield}
\\setlength{\\tabcolsep}{3pt}
\\footnotesize
\\begin{adjustbox}{max width=\\textwidth}
\\begin{tabular}{lcccccc}
\\toprule
 & \\multicolumn{3}{c}{SGT} & \\multicolumn{3}{c}{MPC + GPS policy} \\\\
\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}
Metric & off & on & better & off & on & better \\\\
\\midrule
${shieldRows}\\bottomrule
\\end{tabular}
\\end{adjustbox}
\\end{table*}
`;
const sg = { off: k => pick('sgt_tipping', 'off', k), on: k => pick('sgt_tipping', 'on', k) };
const gp = { off: k => pick('guided_policy', 'off', k), on: k => pick('guided_policy', 'on', k) };
const mean = a => a.reduce((s, v) => s+v, 0)/a.length;
def('shConditions', conditions.length);
def('shSlackOffSgt', f(mean(sg.off('slackPct')), 1));
def('shSlackOnSgt', f(mean(sg.on('slackPct')), 1));
def('shSlackOffGps', f(mean(gp.off('slackPct')), 1));
def('shSlackOnGps', f(mean(gp.on('slackPct')), 1));
def('shAnySlackOff', f(mean([...sg.off('anySlackPct'), ...gp.off('anySlackPct')]), 0));
def('shTensionOffSgt', f(mean(sg.off('meanCoreTension')), 1));
def('shTensionOnSgt', f(mean(sg.on('meanCoreTension')), 1));
def('shProgOffSgt', f(mean(sg.off('progress')), 2));
def('shProgOnSgt', f(mean(sg.on('progress')), 2));
def('shProgGainSgt', f(100*(mean(sg.on('progress'))/mean(sg.off('progress'))-1), 0));
def('shProgBetterSgt', better(sg.on('progress'), sg.off('progress'), 'max'));
def('shAbortOffSgt', f(mean(sg.off('aborts')), 1));
def('shAbortOnSgt', f(mean(sg.on('aborts')), 1));
def('shProgOffGps', f(mean(gp.off('progress')), 2));
def('shProgOnGps', f(mean(gp.on('progress')), 2));
const filtered = runs.filter(r => r.shield === 'on');
def('shFilteredRuns', filtered.length);
def('shClearViol', filtered.filter(r => r.minClearance < 0.08).length);
def('shClearMin', f(Math.min(...filtered.map(r => r.minClearance)), 3));
def('shOuterViol', filtered.filter(r => r.maxOuterTension > 150).length);
def('shMs', f(mean(filtered.map(r => r.controllerMs)), 1));

const sag = read('results/shield_study/sag.json');
def('sagInitialHeight', f(sag.initialHeight, 3));
def('sagMeanHeight', f(sag.meanHeight, 3));
def('sagPercent', f(sag.sagPercent, 0));
def('sagDesignTension', f(sag.pretensionDesign, 0));
def('sagMeanTension', f(sag.meanCoreTension, 1));

writeFileSync(path.join(root, 'results', 'paper', 'numbers_ext.tex'), `% Auto-generated by tools/make_extension_tables.mjs -- do not edit by hand.\n${macros.join('\n')}\n`);
writeFileSync(path.join(root, 'results', 'paper', 'tables_ext.tex'), gpsTable+'\n'+shieldTable);
console.log(macros.join('\n'));
