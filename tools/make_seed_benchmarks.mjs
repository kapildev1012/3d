#!/usr/bin/env node
/**
 * Generate public/default_benchmarks.json: one headless baseline run per
 * level (Levels 1-14), recorded with the same RunRecorder the browser uses.
 *
 *   node tools/make_seed_benchmarks.mjs [--duration 20] [--levels 1,2,3]
 *
 * Each run uses the default interactive configuration of its level (legacy
 * physics core, natural support-face gait, Model A fixed baseline vs Model B
 * adaptive) for --duration seconds of simulated time, or until the mission
 * ends earlier. The file is loaded into a visitor's matrix only when their
 * own store is empty, and every seeded run is labelled SEED.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SimConfig, SphericalRoverModel, TerrainModel, Simulation } from '../js/simEngine.js?v=20261021-ws1';
import { configureLevel, LEVELS } from '../js/levels.js?v=20261021-ws1';
import { RunRecorder } from '../js/runRecorder.js?v=20261021-ws1';
import { emptyState, mergeStates } from '../js/benchmarkCore.js?v=20261021-ws1';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const argValue = (name, fallback) => {
  const index = args.indexOf(name);
  return index >= 0 ? args[index+1] : fallback;
};
const duration = Number(argValue('--duration', 20));
const levels = String(argValue('--levels', LEVELS.map(level => level.id).join(','))).split(',').map(Number);

console.info = () => {};
const collected = [];
const persistence = { upsertRun: run => { if (run.final) collected.push(run); return true; } };

for (const id of levels) {
  const started = Date.now();
  const cfg = configureLevel(new SimConfig({ enableDiagnosticsLog: false }), id);
  const rover = new SphericalRoverModel(cfg);
  const terrain = new TerrainModel(cfg);
  const app = {
    cfg,
    simA: new Simulation(cfg, rover, terrain, 'fixed'),
    simB: new Simulation(cfg, rover, terrain, 'adaptive'),
    obstacleCount: () => (terrain.course ? terrain.course.obstacles.length
      : terrain.expeditionObstacles?.length || terrain.rocks.filter(rock => rock.kind === 'challenge').length),
    constructor: { controllerShortLabel: mode => (mode === 'natural_support_face' ? 'Natural' : mode) }
  };
  const recorder = new RunRecorder(app, persistence);
  recorder.source = 'seed';
  const steps = Math.round(duration/cfg.dt);
  let ended = false;
  for (let k = 0; k < steps && !ended; k++) {
    if (!app.simA.metrics.runTerminal) app.simA.step();
    if (!app.simB.metrics.runTerminal) app.simB.step();
    if (k % 25 === 0) {
      recorder.tick();
      ended = recorder.awaitingReset;
    }
  }
  if (!ended) { recorder.tick(); recorder.finalize('seed-duration', 'terminated'); }
  const run = collected[collected.length-1];
  console.log(`L${String(id).padStart(2)} ${run ? `${run.status.padEnd(10)} B ${run.B.distance.toFixed(2)} m in ${run.simTime.toFixed(1)} s · A ${run.A.distance.toFixed(2)} m` : 'no run'}  (${((Date.now()-started)/1000).toFixed(0)} s wall)`);
}

const state = mergeStates({ ...emptyState(), runs: collected });
state.updatedAt = new Date().toISOString();
state.note = `Headless baseline seed: default configuration per level, ${duration} s of simulated time (or until the mission ends). Generated by tools/make_seed_benchmarks.mjs.`;
mkdirSync(path.join(root, 'public'), { recursive: true });
writeFileSync(path.join(root, 'public', 'default_benchmarks.json'), JSON.stringify(state, null, 1));
console.log(`[seed] wrote public/default_benchmarks.json (${state.runs.length} runs)`);
